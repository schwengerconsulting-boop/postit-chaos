const dictionaries: Record<Lang, Record<MessageKey, string>> = { en, de }

function interpolate(text: string, vars?: Record<string, string | number>): string {
    if (!vars) return text
    return text.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m))
}

/** Translates `key` into `lang`. Unknown placeholders are left as they are. */
export function translate(lang: Lang, key: MessageKey, vars?: Record<string, string | number>): string {
    return interpolate(dictionaries[lang][key] ?? en[key] ?? key, vars)
}

// ---- current language of this process (the browser; the backend passes the language explicitly) ----
let current: Lang = DEFAULT_LANGUAGE

export function setLanguage(lang: Lang) {
    current = lang
}

export function getLanguage(): Lang {
    return current
}

/** Translates `key` into the current language. */
export function t(key: MessageKey, vars?: Record<string, string | number>): string {
    return translate(current, key, vars)
}
