/** Returns "en" or "de" for a case-insensitive match (also "de-DE", "en_US"), otherwise undefined. */
export function parseLang(value: unknown): Lang | undefined {
    if (typeof value !== "string") return undefined
    const v = value.trim().toLowerCase().slice(0, 2)
    return v === "en" || v === "de" ? v : undefined
}

